export function findSkillCategory(skillName: string): string {
  const lower = skillName.toLowerCase();
  for (const cat of SPECIAL_SKILLS_CATALOG) {
    if (cat.skills.some((s) => s.toLowerCase() === lower || lower.includes(s.toLowerCase()))) {
      return cat.shortTitle;
    }
    if (cat.subgroups) {
      for (const sub of cat.subgroups) {
        if (sub.items.some((s) => s.toLowerCase() === lower || lower.includes(s.toLowerCase()))) {
          return `${cat.shortTitle} · ${sub.title}`;
        }
      }
    }
  }
  return "Additional Skill";
}
